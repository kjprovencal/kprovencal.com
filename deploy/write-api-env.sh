#!/usr/bin/env bash
# Write the API environment file to the path given in $1.
# Values come from the environment. This script prints names of missing
# settings, never the values. Do not run it under set -x.
set -euo pipefail
umask 077

if [[ $- == *x* ]]; then
  echo "write-api-env: refusing to run with xtrace (set -x) enabled" >&2
  exit 1
fi

if [[ $# -ne 1 || -z ${1:-} ]]; then
  echo "usage: write-api-env.sh OUTPUT_PATH" >&2
  exit 1
fi
out=$1

trim() {
  local s=$1
  s="${s#"${s%%[![:space:]]*}"}"
  s="${s%"${s##*[![:space:]]}"}"
  printf '%s' "$s"
}

reject_value() {
  local key=$1 value=$2
  if [[ "$value" == *$'\n'* || "$value" == *$'\r'* ]]; then
    echo "write-api-env: ${key} contains a newline" >&2
    exit 1
  fi
  if [[ "$value" == *"'"* ]]; then
    echo "write-api-env: ${key} contains a single quote" >&2
    exit 1
  fi
}

require_value() {
  local key=$1 value=$2
  if [[ -z "$value" ]]; then
    echo "write-api-env: ${key} is required and is not set" >&2
    exit 1
  fi
  reject_value "$key" "$value"
}

session=$(trim "${SESSION_SECRET:-}")
admin=$(trim "${ADMIN_PASSWORD_BCRYPT:-}")
deploy_path=$(trim "${DEPLOY_PATH:-}")
require_value SESSION_SECRET "$session"
require_value ADMIN_PASSWORD_BCRYPT "$admin"
require_value DEPLOY_PATH "$deploy_path"

if [[ ${#session} -lt 32 ]]; then
  echo "write-api-env: SESSION_SECRET must be at least 32 characters" >&2
  exit 1
fi
if [[ "$admin" != '$2'* ]]; then
  echo "write-api-env: ADMIN_PASSWORD_BCRYPT must be a bcrypt hash from cmd/hashpassword" >&2
  exit 1
fi
if [[ "$deploy_path" != /* || "$deploy_path" == */ ]]; then
  echo "write-api-env: DEPLOY_PATH must be an absolute path with no trailing slash" >&2
  exit 1
fi
case "$deploy_path" in
  *[!A-Za-z0-9/_.-]*)
    echo "write-api-env: DEPLOY_PATH contains a character this script will not write" >&2
    exit 1
    ;;
esac

turnstile=$(trim "${TURNSTILE_SECRET_KEY:-}")
cors=$(trim "${CORS_ORIGIN:-}")
log_level=$(trim "${LOG_LEVEL:-}")
log_path=$(trim "${LOG_PATH:-}")
host_status=$(trim "${HOST_STATUS_PATH:-}")
session_hours=$(trim "${ADMIN_SESSION_HOURS:-}")
rate_get=$(trim "${RATE_LIMIT_GET_MAX:-}")
rate_post=$(trim "${RATE_LIMIT_POST_MAX:-}")
rate_off=$(trim "${RATE_LIMIT_DISABLED:-}")
spaces_key=$(trim "${SPACES_KEY:-}")
spaces_secret=$(trim "${SPACES_SECRET:-}")
spaces_bucket=$(trim "${SPACES_BUCKET:-}")
spaces_region=$(trim "${SPACES_REGION:-}")
spaces_endpoint=$(trim "${SPACES_ENDPOINT:-}")

case "$log_level" in
  ""|debug|info|warn|warning|error) ;;
  *)
    echo "write-api-env: LOG_LEVEL must be debug, info, warn, or error" >&2
    exit 1
    ;;
esac
if [[ -n "$cors" && ! "$cors" =~ ^https?://[^/[:space:]]+ ]]; then
  echo "write-api-env: CORS_ORIGIN must be an http or https origin" >&2
  exit 1
fi
if [[ -n "$session_hours" && ! "$session_hours" =~ ^[0-9]+([.][0-9]+)?$ ]]; then
  echo "write-api-env: ADMIN_SESSION_HOURS must be a number from 1 to 720" >&2
  exit 1
fi
if [[ -n "$rate_off" && "$rate_off" != "1" ]]; then
  echo "write-api-env: RATE_LIMIT_DISABLED must be 1 when set" >&2
  exit 1
fi

missing_spaces=()
[[ -z "$spaces_key" ]] && missing_spaces+=(SPACES_KEY)
[[ -z "$spaces_secret" ]] && missing_spaces+=(SPACES_SECRET)
[[ -z "$spaces_bucket" ]] && missing_spaces+=(SPACES_BUCKET)
[[ -z "$spaces_region" ]] && missing_spaces+=(SPACES_REGION)
[[ -z "$spaces_endpoint" ]] && missing_spaces+=(SPACES_ENDPOINT)
if [[ ${#missing_spaces[@]} -gt 0 && ${#missing_spaces[@]} -lt 5 ]]; then
  echo "write-api-env: set all of SPACES_KEY, SPACES_SECRET, SPACES_BUCKET, SPACES_REGION, and SPACES_ENDPOINT, or leave them all empty. Missing: ${missing_spaces[*]}" >&2
  exit 1
fi

for key in TURNSTILE_SECRET_KEY CORS_ORIGIN LOG_PATH HOST_STATUS_PATH SPACES_KEY SPACES_SECRET SPACES_BUCKET SPACES_REGION SPACES_ENDPOINT; do
  reject_value "$key" "$(trim "${!key:-}")"
done
for key in RATE_LIMIT_GET_MAX RATE_LIMIT_POST_MAX; do
  value=$(trim "${!key:-}")
  reject_value "$key" "$value"
  if [[ -n "$value" && ! "$value" =~ ^[0-9]+$ ]]; then
    echo "write-api-env: ${key} must be a positive integer" >&2
    exit 1
  fi
done

tmp=$(mktemp "${TMPDIR:-/tmp}/personal-site-api.env.XXXXXX")
trap 'rm -f "$tmp"' EXIT

{
  printf '%s\n' '# Generated by deploy/write-api-env.sh. The next deploy overwrites this file.'
  printf "%s='%s'\n" LISTEN_ADDR '127.0.0.1:8080'
  printf "%s='%s'\n" APP_ENV production
  printf "%s='%s'\n" TRUST_PROXY 1
  printf "%s='%s'\n" BADGER_PATH "${deploy_path}/data/badger"
  printf "%s='%s'\n" SESSION_SECRET "$session"
  printf "%s='%s'\n" ADMIN_PASSWORD_BCRYPT "$admin"
  [[ -n "$turnstile" ]] && printf "%s='%s'\n" TURNSTILE_SECRET_KEY "$turnstile"
  [[ -n "$cors" ]] && printf "%s='%s'\n" CORS_ORIGIN "$cors"
  [[ -n "$log_level" ]] && printf "%s='%s'\n" LOG_LEVEL "$log_level"
  [[ -n "$log_path" ]] && printf "%s='%s'\n" LOG_PATH "$log_path"
  [[ -n "$host_status" ]] && printf "%s='%s'\n" HOST_STATUS_PATH "$host_status"
  [[ -n "$session_hours" ]] && printf "%s='%s'\n" ADMIN_SESSION_HOURS "$session_hours"
  [[ -n "$rate_get" ]] && printf "%s='%s'\n" RATE_LIMIT_GET_MAX "$rate_get"
  [[ -n "$rate_post" ]] && printf "%s='%s'\n" RATE_LIMIT_POST_MAX "$rate_post"
  [[ -n "$rate_off" ]] && printf "%s='%s'\n" RATE_LIMIT_DISABLED "$rate_off"
  if [[ ${#missing_spaces[@]} -eq 0 ]]; then
    printf "%s='%s'\n" SPACES_KEY "$spaces_key"
    printf "%s='%s'\n" SPACES_SECRET "$spaces_secret"
    printf "%s='%s'\n" SPACES_BUCKET "$spaces_bucket"
    printf "%s='%s'\n" SPACES_REGION "$spaces_region"
    printf "%s='%s'\n" SPACES_ENDPOINT "$spaces_endpoint"
  fi
} > "$tmp"

mv "$tmp" "$out"
trap - EXIT
chmod 600 "$out"
